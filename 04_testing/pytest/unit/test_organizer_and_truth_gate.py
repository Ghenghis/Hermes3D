"""Unit tests — small, fast, real code paths only."""
from __future__ import annotations

import tempfile
from pathlib import Path

import pytest
import trimesh

from hermes3d.core.design import OrganizerSpec, build_organizer, export_organizer
from hermes3d.core.validation import (
    CheckStatus,
    TruthGateConfig,
    run_truth_gate,
)


# ---------------------------------------------------------------------------
# OrganizerSpec.validated()
# ---------------------------------------------------------------------------


class TestOrganizerSpec:
    def test_default_is_valid(self) -> None:
        spec = OrganizerSpec().validated()
        assert spec.width_mm > 0 and spec.depth_mm > 0 and spec.height_mm > 0

    def test_negative_width_rejected(self) -> None:
        with pytest.raises(ValueError):
            OrganizerSpec(width_mm=-1).validated()

    def test_zero_wall_rejected(self) -> None:
        with pytest.raises(ValueError):
            OrganizerSpec(wall_mm=0).validated()

    def test_too_many_trays_rejected(self) -> None:
        # 100mm width with 2mm walls and N trays: each compartment is
        # (96 - (N-1)*2) / N. For N=50 that's negative.
        with pytest.raises(ValueError):
            build_organizer(OrganizerSpec(width_mm=100, tray_count=50))

    def test_signature_is_deterministic(self) -> None:
        a = OrganizerSpec().signature()
        b = OrganizerSpec().signature()
        assert a == b
        assert len(a) == 10

    def test_signature_changes_with_params(self) -> None:
        a = OrganizerSpec().signature()
        b = OrganizerSpec(width_mm=200).signature()
        assert a != b


